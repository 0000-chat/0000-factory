import { refs } from './model.mjs';
import { isAccepted } from './planning.mjs';
import { taskCodeForId } from './task-codes.mjs';

function isCurrent(item) {
  return item.data.status !== 'done';
}

function link(item, suffix = '') {
  return `[${item.data.id} (${taskCodeForId(item.data.id)})](../../${item.path})${suffix}`;
}

function table(headers, rows) {
  return `| ${headers.join(' | ')} |\n| ${headers.map(() => '---').join(' | ')} |\n${rows.map(row => `| ${row.join(' | ')} |`).join('\n')}\n`;
}

function oneTrailingNewline(value) {
  return `${value.replace(/\n+$/g, '')}\n`;
}

function nextStep(item) {
  return item.body.split('## Next step')[1]?.split('##')[0]?.trim().split('\n')[0] ?? '—';
}

function parentId(item) {
  return refs(item.data.parent)[0] ?? null;
}

function childrenMap(items) {
  const children = new Map();
  for (const item of items) {
    const parent = parentId(item);
    if (!parent) continue;
    const list = children.get(parent) ?? [];
    list.push(item);
    children.set(parent, list);
  }
  for (const list of children.values()) list.sort((a, b) => a.data.id.localeCompare(b.data.id));
  return children;
}

function contextForAccepted(items) {
  const byId = new Map(items.map(item => [item.data.id, item]));
  const included = new Set(items.filter(item => isAccepted(item) && isCurrent(item)).map(item => item.data.id));
  const contextual = new Set();
  for (const id of [...included]) {
    let current = byId.get(id);
    while (current) {
      const parent = byId.get(parentId(current));
      if (!parent) break;
      if (!included.has(parent.data.id)) contextual.add(parent.data.id);
      current = parent;
    }
  }
  return { byId, included, contextual };
}

function treeRows(items) {
  const { byId, included, contextual } = contextForAccepted(items);
  const visible = new Set([...included, ...contextual]);
  const children = childrenMap(items.filter(item => visible.has(item.data.id)));
  const roots = items.filter(item => visible.has(item.data.id) && !visible.has(parentId(item)))
    .sort((a, b) => a.data.id.localeCompare(b.data.id));
  const rows = [];
  const visit = (item, depth) => {
    const context = contextual.has(item.data.id);
    rows.push({ item, depth, context });
    for (const child of children.get(item.data.id) ?? []) visit(child, depth + 1);
  };
  for (const root of roots) visit(root, 0);
  // A malformed relationship should still produce a useful view for every
  // loaded accepted item; validation reports the relationship separately.
  for (const item of items.filter(candidate => visible.has(candidate.data.id))) {
    if (!rows.some(row => row.item.data.id === item.data.id)) visit(item, 0);
  }
  return rows.map(({ item, depth, context }) => ({
    item,
    label: `${'  '.repeat(depth)}${link(item, context ? ` *(${item.data.commitment} context)*` : '')}`,
    context
  }));
}

function dependencyRef(id, byId) {
  const item = byId.get(id);
  if (!item) return `${id} *(missing)*`;
  return link(item, item.data.commitment === 'accepted' ? '' : ` *(${item.data.commitment})*`);
}

export function renderViews(data) {
  const items = data.items ?? [];
  const { byId } = contextForAccepted(items);
  const rows = treeRows(items);
  const acceptedCurrent = items.filter(item => isAccepted(item) && isCurrent(item)).sort((a, b) => a.data.id.localeCompare(b.data.id));
  const owners = [...new Set(acceptedCurrent.map(item => item.data.owner))].sort();

  const active = '# Current work\n\nGenerated by `node tooling/tracker/cli.mjs build`. Edit item files, then rebuild. Draft and planned parents remain as labelled context when they contain accepted work.\n\n' + table(
    ['Item', 'Owner', 'Status', 'Phase', 'Next step'],
    rows.map(({ item, label, context }) => [
      label,
      context ? '—' : item.data.owner,
      context ? `${item.data.commitment} context` : item.data.status,
      item.data.phase,
      context ? '—' : nextStep(item)
    ])
  );

  const byOwner = '# Work by owner\n\nGenerated from accepted current items. Draft and planned items are omitted.\n\n' + owners.map(owner => `## ${owner}\n\n${acceptedCurrent.filter(item => item.data.owner === owner).map(item => `- ${link(item)} — ${item.data.status} (${item.data.phase})`).join('\n')}\n`).join('\n');

  const dependencyItems = items.filter(item => isCurrent(item)).sort((a, b) => a.data.id.localeCompare(b.data.id));
  const dependencies = '# Dependencies\n\nGenerated from live item IDs. Parent links define the tree; dependency links may cross buckets. Draft and planned references are labelled explicitly.\n\n' + table(
    ['Item', 'Parent', 'Depends on'],
    dependencyItems.map(item => [
      link(item, item.data.commitment === 'accepted' ? '' : ` *(${item.data.commitment})*`),
      parentId(item) ? dependencyRef(parentId(item), byId) : '—',
      refs(item.data.depends_on).map(id => dependencyRef(id, byId)).join(', ') || '—'
    ])
  );

  const releases = '# Releases\n\nGenerated from release records. A gate is complete only with evidence in its release file.\n\n' + (data.releases ?? []).sort((a, b) => a.data.id.localeCompare(b.data.id)).map(x => `## [${x.data.id}](../../${x.path})\n\nProject: ${x.data.project} · Owner: ${x.data.owner} · Status: ${x.data.status} · Target: ${x.data.target ?? 'unknown'}\n\n${x.body.split('## Gates')[1]?.split('##')[0]?.trim() ?? ''}\n`).join('\n');
  return {
    'tracker/views/now.md': oneTrailingNewline(active),
    'tracker/views/owners.md': oneTrailingNewline(byOwner),
    'tracker/views/dependencies.md': oneTrailingNewline(dependencies),
    'tracker/views/releases.md': oneTrailingNewline(releases)
  };
}
